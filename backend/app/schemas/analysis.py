from datetime import datetime
from typing import Any, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator
from backend.app.models.analysis import ConfidenceLevel
from backend.app.schemas.knowledge import SimilarIncidentReference


class StructuredRCAResponse(BaseModel):
    """
    Schema for structured JSON output generated by LLM provider.
    """
    probable_root_cause: str = Field(
        description="The primary, specific technical cause of the incident based on evidence"
    )
    explanation: str = Field(
        description="Detailed narrative describing the failure mechanism step by step"
    )
    supporting_evidence: List[str] = Field(
        default_factory=list,
        description="Direct references to timestamps, error messages, or logs from the provided evidence"
    )
    contributing_factors: List[str] = Field(
        default_factory=list,
        description="Secondary or environmental factors that contributed to the incident"
    )
    confidence_level: ConfidenceLevel = Field(
        default=ConfidenceLevel.LOW,
        description="Confidence level (LOW, MEDIUM, HIGH) based on evidence completeness"
    )
    recommended_actions: List[str] = Field(
        default_factory=list,
        description="Concrete, actionable troubleshooting and remediation steps"
    )
    limitations: List[str] = Field(
        default_factory=list,
        description="Caveats, missing telemetry, or assumptions due to incomplete evidence"
    )

    @field_validator("confidence_level", mode="before")
    @classmethod
    def parse_confidence(cls, v: Any) -> ConfidenceLevel:
        if isinstance(v, ConfidenceLevel):
            return v
        return ConfidenceLevel.from_string(str(v))


class RCARequest(BaseModel):
    """
    Optional payload for triggering root-cause analysis on an incident.
    """
    additional_context: Optional[str] = Field(
        default=None,
        max_length=2000,
        description="Optional operator notes or context to aid the analysis"
    )
    max_evidence_logs: Optional[int] = Field(
        default=None,
        ge=1,
        le=100,
        description="Custom limit for number of recent logs to include as evidence"
    )


class AnalysisResponse(BaseModel):
    """
    Public representation of an incident root-cause analysis.
    """
    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    id: str
    analysis_id: str
    incident_id: str
    user_id: str
    probable_root_cause: str
    explanation: str
    supporting_evidence: List[str]
    contributing_factors: List[str]
    confidence_level: ConfidenceLevel
    recommended_actions: List[str]
    limitations: List[str]
    provider: str
    model: str
    evidence_log_count: int
    redacted_secrets_count: int
    rag_status: str = Field(default="DISABLED", description="Status of historical RAG retrieval: SUCCESS, EMPTY, UNAVAILABLE, DISABLED")
    similar_incidents: List[SimilarIncidentReference] = Field(default_factory=list, description="References to similar historical incidents retrieved via RAG")
    created_at: datetime

    @model_validator(mode="before")
    @classmethod
    def map_id_field(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "id" not in data and "_id" in data:
                data["id"] = str(data["_id"])
            elif "id" in data:
                data["id"] = str(data["id"])
        elif hasattr(data, "_id") and not hasattr(data, "id"):
            setattr(data, "id", str(getattr(data, "_id")))
        return data


class PaginatedAnalysisResponse(BaseModel):
    """
    Paginated root-cause analysis query results.
    """
    items: List[AnalysisResponse]
    total: int
    limit: int
    offset: int
