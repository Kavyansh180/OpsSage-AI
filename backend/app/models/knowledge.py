from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class HistoricalAnalysisSummary(BaseModel):
    """
    Encapsulates AI-generated RCA hypotheses attached to a historical incident.
    Explicitly treated as AI hypothesis, NOT as confirmed resolution.
    """
    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    analysis_id: Optional[str] = None
    probable_root_cause: str
    explanation: str
    recommended_actions: List[str] = Field(default_factory=list)
    confidence_level: str = "LOW"


class KnowledgeDocumentInDB(BaseModel):
    """
    Internal model representing a historical knowledge base document in MongoDB.
    Stored in the 'knowledge_base' collection with vector embeddings.
    """
    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    id: Optional[str] = Field(default=None, alias="_id")
    knowledge_id: str = Field(description="Unique human-readable identifier (e.g. KB-20261118-A1B2C3)")
    source_incident_id: str = Field(description="ID of the original incident this knowledge was built from")
    incident_ref_id: Optional[str] = Field(default=None, description="Compatibility alias for source_incident_id")
    user_id: str = Field(description="Tenant / owner ID")
    service_name: str = Field(description="Target service name")
    environment: str = Field(description="Runtime environment (production, staging, etc.)")
    error_signature: str = Field(description="Deterministic error signature hash")
    title: str = Field(description="Incident summary title")
    description: Optional[str] = Field(default=None, description="Additional context or summary")
    diagnostic_summary: str = Field(description="Sanitized summary of errors and diagnostic evidence")
    historical_analysis: Optional[HistoricalAnalysisSummary] = Field(
        default=None,
        description="Historical AI RCA hypothesis (untrusted supporting context)"
    )
    confirmed_resolution: Optional[str] = Field(
        default=None,
        description="Engineer-confirmed remediation steps (only present if verified by engineer)"
    )
    has_verified_resolution: bool = Field(
        default=False,
        description="Explicit flag: True only if confirmed_resolution is verified by an engineer"
    )
    embedding: List[float] = Field(
        description="384-dimensional vector embedding generated by sentence-transformers/all-MiniLM-L6-v2"
    )
    source_metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Provenance metadata (event counts, dates, versions)"
    )
    created_at: datetime
    updated_at: datetime
